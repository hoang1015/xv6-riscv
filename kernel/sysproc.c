uint64
sys_kpanic(void)
{
  printf("kernel: sys_kpanic() called by pid %d. Intentionally causing NULL pointer access...\n", myproc()->pid);
  
  // Đây là "lỗi truy cập con trỏ NULL trong kernel space"
  *(volatile int *)0 = 42;
  
  // Kernel sẽ panic trước khi đến được đây.
  return 0;
}
